export const rtcOriginalPrompts: Sentence[] = source.map((line) => {
  const segments = line.split(' ').flatMap((token) => {
    const [text, reading] = token.split(':')
    return reading
      ? [{ text, reading }]
      : Array.from(text, (text) => ({ text, reading: normalizeReading(text) }))
  })
  return {
    text: segments.map((s) => s.text).join(''),
    reading: segments.map((s) => s.reading).join(''),
    segments,
  }
})
export const isRtcOriginal = (id: string) => id === 'cpu-rtc'
export const rtcOriginalPassage: Passage = {
  id: 'cpu-rtc',
  title: 'RTCオリジナル',
  genre: 'RTC準拠',
  accent: 'RTC',
  subtitle: `${rtcOriginalPrompts.length}文の独自短文から、重複なしでランダムに15問出題。`,
  source: { label: 'GALACTYPE独自原稿', kind: 'provided' },
  paragraphs: [],
}
export function rtcOriginalDocument(seed: string) {
  const pool = [...rtcOriginalPrompts]
  const random = seededRandom(`original-v1/${seed}`)
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  const sentences = pool.slice(0, 15)
  return {
    passage: { ...rtcOriginalPassage, paragraphs: sentences },
    sentences,
    plan: null,
  }
}
